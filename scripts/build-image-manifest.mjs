import { readdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";

export const SUPPORTED_IMAGE_EXTENSIONS = new Set([".webp", ".jpg", ".jpeg", ".png", ".avif"]);
const naturalCollator = new Intl.Collator("en", { numeric: true, sensitivity: "base" });

function extension(filename) {
  const dot = filename.lastIndexOf(".");
  return dot < 0 ? "" : filename.slice(dot).toLowerCase();
}

function webPath(...parts) {
  return parts.join("/").split(sep).join("/");
}

async function readMetadata(directory, files, warnings) {
  const configs = files.filter((entry) => entry.isFile() && !entry.name.startsWith(".") && entry.name.endsWith(".config.json"));
  if (!configs.length) return {};
  configs.sort((a, b) => naturalCollator.compare(a.name, b.name));
  if (configs.length > 1) warnings.push(`${webPath(relative(process.cwd(), directory))}: multiple metadata files found; using ${configs[0].name}`);
  try {
    const value = JSON.parse(await readFile(resolve(directory, configs[0].name), "utf8"));
    if (!value || Array.isArray(value) || typeof value !== "object") throw new Error("the root value must be an object");
    return value;
  } catch (error) {
    throw new Error(`Invalid image metadata ${resolve(directory, configs[0].name)}: ${error.message}`);
  }
}

function metadataFor(filename, metadata, collection, warnings) {
  const raw = metadata[filename];
  if (raw === undefined) return { position: "center" };
  if (!raw || Array.isArray(raw) || typeof raw !== "object") {
    warnings.push(`${collection}/${filename}: metadata must be an object; using defaults`);
    return { position: "center" };
  }
  const result = { position: "center" };
  for (const field of ["position", "alt", "caption"]) {
    if (raw[field] === undefined) continue;
    if (typeof raw[field] !== "string" || !raw[field].trim()) {
      warnings.push(`${collection}/${filename}: ${field} must be a non-empty string; ignoring it`);
    } else {
      result[field] = raw[field].trim();
    }
  }
  return result;
}

export async function createImageManifest({ imagesRoot = resolve("assets/images") } = {}) {
  const collections = {};
  const warnings = [];

  async function scan(directory) {
    let entries;
    try {
      entries = await readdir(directory, { withFileTypes: true });
    } catch (error) {
      if (error.code === "ENOENT" && directory === imagesRoot) return;
      throw error;
    }
    entries = entries.filter((entry) => !entry.name.startsWith(".")).sort((a, b) => naturalCollator.compare(a.name, b.name));
    const collection = webPath(relative(imagesRoot, directory));
    const images = entries.filter((entry) => entry.isFile() && SUPPORTED_IMAGE_EXTENSIONS.has(extension(entry.name)))
      .sort((a, b) => naturalCollator.compare(a.name, b.name));
    const hasConfig = entries.some((entry) => entry.isFile() && entry.name.endsWith(".config.json"));

    if (collection && (images.length || hasConfig)) {
      const metadata = await readMetadata(directory, entries, warnings);
      const names = new Set(images.map((entry) => entry.name));
      for (const filename of Object.keys(metadata).sort(naturalCollator.compare)) {
        if (!names.has(filename)) warnings.push(`${collection}: metadata references missing image ${filename}`);
      }
      collections[collection] = images.map(({ name }) => ({
        src: webPath("assets/images", collection, name),
        ...metadataFor(name, metadata, collection, warnings),
      }));
      if (!images.length) warnings.push(`${collection}: collection is empty`);
    }

    for (const entry of entries) {
      if (entry.isDirectory()) await scan(resolve(directory, entry.name));
    }
  }

  await scan(imagesRoot);
  return { schemaVersion: 1, collections, warnings };
}

export function serializeManifest(manifest) {
  return `/* AUTO-GENERATED by npm run images:build. DO NOT EDIT. */\nwindow.WEDDING_IMAGE_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;
}

export async function buildImageManifest({ imagesRoot = resolve("assets/images"), output = resolve("assets/data/images.generated.js"), check = false } = {}) {
  const manifest = await createImageManifest({ imagesRoot });
  const generated = serializeManifest(manifest);
  if (check) {
    let current = "";
    try { current = await readFile(output, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
    if (current !== generated) throw new Error("Image manifest is stale. Run `npm run images:build` and commit the result.");
  } else {
    await writeFile(output, generated);
  }
  for (const warning of manifest.warnings) console.warn(`[images] ${warning}`);
  return manifest;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  buildImageManifest({ check: process.argv.includes("--check") }).catch((error) => {
    console.error(`[images] ${error.message}`);
    process.exitCode = 1;
  });
}
